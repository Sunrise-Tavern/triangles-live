"""The effect vocabulary.

Every ``E_*`` parameter name here was verified against the xLights 2026.15
binary rather than harvested from the existing sequences in this show folder --
one of those files has an ``On`` effect whose ``ref`` points at a ``Bars``
settings string, so harvesting would have propagated that corruption.

Two properties keep this safe:

* xLights fills in defaults for any setting we omit, so a partial settings
  string always renders.  We only emit parameters we actually mean.
* xLights ignores settings it does not recognise.  The one thing that must be
  right is the effect's display ``name``, which is why EFFECT_NAMES is closed.

``T_*`` keys are layer/timing settings shared by every effect; ``B_*`` are
render-buffer settings.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

_REGISTRY_PATH = Path(__file__).resolve().parent.parent / "effect_registry.json"


def _load_registry() -> dict[str, dict]:
    """Effect definitions extracted from the installed xLights app bundle.

    Generated by ``build_registry.py`` from xLights' own effect metadata, so the
    vocabulary is whatever the installed version actually supports rather than a
    hand-kept subset. Re-run that script after upgrading xLights.
    """
    try:
        return json.loads(_REGISTRY_PATH.read_text())["effects"]
    except (OSError, ValueError, KeyError):
        # Without the registry only the curated builders below work; they carry
        # their own verified parameter names, so this degrades rather than dies.
        return {}


REGISTRY = _load_registry()

#: Effect display names, exactly as xLights writes them in the `name` attribute.
#: Only these may be emitted.
EFFECT_NAMES = frozenset(REGISTRY) or frozenset({
    "On", "Bars", "Color Wash", "Spirals", "Butterfly", "Pinwheel",
    "Ripple", "Shockwave", "Twinkle", "Fan", "Galaxy", "Meteors",
})


@dataclass(frozen=True)
class EffectSpec:
    """One effect instance: its display name plus its settings."""

    name: str
    settings: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        if self.name not in EFFECT_NAMES:
            raise ValueError(
                f"Unknown xLights effect {self.name!r}. Known: {sorted(EFFECT_NAMES)}"
            )

    def serialize(self) -> str:
        return ",".join(f"{k}={self.settings[k]}" for k in sorted(self.settings))


def _format(info: dict, value) -> str:
    """Render one parameter value the way xLights stores it."""
    ty = info.get("type")

    if ty == "bool":
        return "1" if value else "0"

    if ty == "enum":
        options = info.get("options") or []
        if options and value not in options:
            raise ValueError(
                f"{info['key']}: {value!r} is not one of {options}"
            )
        return str(value)

    if ty in ("int", "float"):
        lo, hi = info.get("min"), info.get("max")
        # A few entries carry a range that contradicts their own default --
        # Wave_Number_Waves defaults to 2.5 with a stated range of [180, 3600].
        # Where the metadata disagrees with itself, clamping would turn a
        # sensible value into a wrong one, so leave it alone.
        default = info.get("default")
        trustworthy = not (
            isinstance(default, (int, float)) and not isinstance(default, bool)
            and ((lo is not None and default < lo)
                 or (hi is not None and default > hi))
        )
        if trustworthy:
            if lo is not None:
                value = max(lo, value)
            if hi is not None:
                value = min(hi, value)
        # A float slider is stored through a text control, so it keeps decimals;
        # an int slider is stored as a plain integer.
        if ty == "float" or info.get("divisor"):
            return f"{float(value):.2f}"
        return str(int(round(value)))

    return str(value)


def build(name: str, *, fade_in: float = 0.0, fade_out: float = 0.0,
          buffer_style: str | None = None, **params) -> EffectSpec:
    """Build any effect the installed xLights supports, by name.

    Parameters are given by their metadata id (``Plasma_Style``, ``Warp_Type``)
    and are checked against the registry: unknown names raise, numbers are
    clamped to the effect's own range, and enum values must be one of the
    options xLights offers. That check is the point -- xLights silently ignores
    settings it does not recognise, so a typo would otherwise show up only as an
    effect mysteriously rendering with defaults.

    The curated builders below stay as the convenient path for the effects used
    most; this covers everything else.
    """
    if name not in REGISTRY:
        raise ValueError(
            f"Unknown xLights effect {name!r}. "
            f"Run build_registry.py if you have upgraded xLights."
        )
    spec = REGISTRY[name]["params"]

    settings = _layer(fade_in, fade_out)
    for pid, value in params.items():
        if pid not in spec:
            close = [k for k in spec if pid.lower() in k.lower()]
            raise ValueError(
                f"{name!r} has no parameter {pid!r}."
                + (f" Did you mean {close}?" if close else
                   f" Available: {sorted(spec)[:12]}...")
            )
        settings[spec[pid]["key"]] = _format(spec[pid], value)

    if buffer_style:
        settings["B_CHOICE_BufferStyle"] = buffer_style
    return EffectSpec(name, settings)


def defaults_for(name: str) -> dict[str, object]:
    """Every parameter of an effect with its xLights default. For exploring."""
    return {pid: info.get("default")
            for pid, info in REGISTRY.get(name, {}).get("params", {}).items()}


def with_fade(spec: EffectSpec, *, fade_in: float | None = None,
              fade_out: float | None = None) -> EffectSpec:
    """A copy of `spec` with its layer fades overridden.

    Lets a caller adjust the fade on an already-built effect without every
    builder having to thread the parameter through.
    """
    s = dict(spec.settings)
    if fade_in is not None:
        s["T_TEXTCTRL_Fadein"] = f"{max(0.0, fade_in):.2f}"
    if fade_out is not None:
        s["T_TEXTCTRL_Fadeout"] = f"{max(0.0, fade_out):.2f}"
    return EffectSpec(spec.name, s)


def _layer(fade_in: float = 0.0, fade_out: float = 0.0, **extra: object) -> dict[str, str]:
    """Common T_* layer settings.

    Fades are in seconds and are what make effects feel musical rather than
    switched -- almost every builder below takes them.
    """
    s = {
        "T_CHECKBOX_Canvas": "0",
        "T_CHECKBOX_LayerMorph": "0",
        "T_CHOICE_LayerMethod": "Normal",
        "T_SLIDER_EffectLayerMix": "0",
        "T_TEXTCTRL_Fadein": f"{max(0.0, fade_in):.2f}",
        "T_TEXTCTRL_Fadeout": f"{max(0.0, fade_out):.2f}",
    }
    s.update({k: str(v) for k, v in extra.items()})
    return s


