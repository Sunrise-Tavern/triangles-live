def on(brightness: int = 100, *, fade_in: float = 0.0, fade_out: float = 0.0,
       shimmer: bool = False, end_brightness: int | None = None) -> EffectSpec:
    """Flat color. The workhorse for accents, strobes and the DJ par.

    `brightness` ramps to `end_brightness` across the effect if given.
    """
    end = brightness if end_brightness is None else end_brightness
    return EffectSpec("On", {
        "E_TEXTCTRL_Eff_On_Start": str(int(brightness)),
        "E_TEXTCTRL_Eff_On_End": str(int(end)),
        "E_CHECKBOX_On_Shimmer": "1" if shimmer else "0",
        **_layer(fade_in, fade_out),
    })


def bars(count: int = 3, direction: str = "up", cycles: float = 1.0, *,
         gradient: bool = True, three_d: bool = False,
         fade_in: float = 0.0, fade_out: float = 0.0,
         buffer_style: str | None = None) -> EffectSpec:
    """Moving bars. Direction is one of up/down/left/right/expand/compress
    or their 'Alternate *' variants."""
    s = {
        "E_SLIDER_Bars_BarCount": str(int(count)),
        "E_CHOICE_Bars_Direction": direction,
        "E_TEXTCTRL_Bars_Cycles": f"{cycles:.2f}",
        "E_CHECKBOX_Bars_3D": "1" if three_d else "0",
        "E_CHECKBOX_Bars_Highlight": "0",
        "E_CHECKBOX_Bars_Gradient": "1" if gradient else "0",
        **_layer(fade_in, fade_out),
    }
    if buffer_style:
        s["B_CHOICE_BufferStyle"] = buffer_style
    return EffectSpec("Bars", s)


